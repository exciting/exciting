!> Miscellaneous variables 
Module mod_misc
  Use modinput
  use precision, only: str_1024, str_256, i32, dp
  implicit none

  private
  
  !> Code version
  character(40), public :: versionname = 'SODIUM'

  !> Build date of current version
  integer(i32), public :: version(3)

  !> git hash value of current build at HEAD
  character(40), public :: githash

  !> Compiler used to build current version
  character(str_1024), public :: compiler_version

  !> filename extension for files generated by gndstate
  Character (str_256), public :: filext
  !> Default file extension
  Data filext / '.OUT' /

  !> reference version for LDA+U
  integer(i32), parameter, public:: refversion_ldapu(3) = (/ 0, 9, 131 /)
  !> reference version for new exciting
  integer(i32), parameter, public :: refversion_new(3) = (/ 0, 9, 224 /)
  !> reference version (date-based) for githash in STATE.OUT file
  integer(i32), parameter, public :: refversion_gitstate(3) = (/ 10, 4, 14 /)
  
  !> maximum number of tasks
  Integer(i32), Parameter, public :: maxtasks = 40
  !> number of tasks
  Integer(i32), public :: ntasks
  !> task array
  Integer(i32), public :: tasks (maxtasks)
  !> current task
  Integer(i32), public :: task
  
  !> tstop is .true. if STOP file exists
  Logical, public :: tstop
  !> tlast is .true. if self-consistent loop is on the last iteration
  Logical, public :: tlast
  
  !> Scratch space path
  Character (str_256), public :: scrpath
  !> Maximum number of note lines
  Integer(i32), Parameter, public :: maxnlns = 20
  !> Number of note lines
  Integer(i32), public :: notelns
  !> Notes to include in INFO.OUT
  Character (80), public :: notes (maxnlns)

End Module mod_misc

